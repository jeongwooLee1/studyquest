// 변형은 보기 순서를 정해진 칸만큼 돌려서 정답 자리가 한쪽(②)에 몰리지 않게 한다(keepOrder 문항은 그대로)
const rot = (v: C, k: number): C => {
  const n = v.options.length; if (v.keepOrder || !(k % n)) return v;
  const to = (a: number) => ((a - 1 + k) % n) + 1; // 옛 번호 → 새 번호
  const options = v.options.map((_, i) => v.options[(i - k % n + n) % n]);
  return { ...v, options, answer: to(v.answer), traps: (v.traps || []).map((t) => ({ ...t, a: to(t.a) })) };
};
